/*
    add 加, R-Type, RV32I and RV64I,         x[rd] = x[rs1] + x[rs2], 忽略算术溢出
    +--------------------------------------------------------------------------------------------------+
    |31                   25|24         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        0000000        |     rs2     |     rs1     |   000   |     rd     |        0110011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_add = opcode_is_0110011 & funct3_is_000 & funct7_is_0000000;

/*
    addi 加立即数, I-Type, RV32I and RV64I,     x[rd] = x[rs1] + sext[imm[11 : 0]];
    加符号位扩展的立即数加到寄存器x[rs1]上, 并将结果写入x[rd], 忽略算术溢出
    +--------------------------------------------------------------------------------------------------+
    |31                                 20|19         15|14     12|11         7|6                     0|
    +-------------------------------------+-------------+---------+------------+-----------------------+
    |               imm[11:0]             |     rs1     |   000   |     rd     |        0010011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_addi = opcode_is_0010011 & funct3_is_000;

/*
    and 与, R-Type, RV32I and RV64I,                     x[rd] = x[rs1] & x[rs2];
    将寄存器x[rs1]和寄存器x[rs2]位与的结果写入x[rd]寄存器.
    +--------------------------------------------------------------------------------------------------+
    |31                   25|24         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        0000000        |     rs2     |     rs1     |   111   |     rd     |        0110011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_and = opcode_is_0110011 & funct3_is_111 & funct7_is_0000000;

/*
    andi 与立即数, I-Type, RV32I and RV64I, x[rd] = x[rs1] & sext(imm[11 : 0]);
    把符号位扩展的立即数和寄存器x[rs1]位与的结果写入x[rd]寄存器.
    +--------------------------------------------------------------------------------------------------+
    |31                                 20|19         15|14     12|11         7|6                     0|
    +-------------------------------------+-------------+---------+------------+-----------------------+
    |               imm[11:0]             |     rs1     |   111   |     rd     |        0010011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_andi = opcode_is_0010011 & funct3_is_111;

/*
    auipc PC加立即数, U-Type, x[rd] = PC + sext(imm[31 : 12] << 12);
    把符号位扩展的20位(左移12位)立即数加到PC上, 并将结果写入x[rd].
    +--------------------------------------------------------------------------------------------------+
    |31                                                         12|11         7|6                     0|
    +-------------------------------------------------------------+------------+-----------------------+
    |                         imm[31:12]                          |     rd     |        0010111        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_auipc = opcode_is_0010111;

/*
    lui 高位立即数加载, U Type, RV32I and RV64I, x[rd] = sext(imm[31 : 12] << 12);
    将符号位扩展的20位立即数imm左移12位, 并将低12位置0, 写入x[rd]中.
    +--------------------------------------------------------------------------------------------------+
    |31                                                         12|11         7|6                     0|
    +-------------------------------------------------------------+------------+-----------------------+
    |                         imm[31:12]                          |     rd     |        0110111        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_lui = opcode_is_0110111;

/*
    or 或, R-Type, RV32I and RV64I,                     x[rd] = x[rs1] | x[rs2];
    将寄存器x[rs1]和寄存器x[rs2]位或的结果写入x[rd]寄存器.
    +--------------------------------------------------------------------------------------------------+
    |31                   25|24         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        0000000        |     rs2     |     rs1     |   110   |     rd     |        0110011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_or = opcode_is_0110011 & funct3_is_110 & funct7_is_0000000;

/*
    ori 立即数或, R-Type, RV32I and RV64I,               x[rd] = x[rs1] | sext(imm);
    将寄存器x[rs1]和寄存器x[rs2]位或的结果写入x[rd]寄存器.
    +--------------------------------------------------------------------------------------------------+
    |31                                 20|19         15|14     12|11         7|6                     0|
    +-------------------------------------+-------------+---------+------------+-----------------------+
    |               imm[11:0]             |     rs1     |   110   |     rd     |        0010011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_ori = opcode_is_0010011 & funct3_is_110;

/*
    sll    rd, rs1, rs2                                                 x[rd] = x[rs1] << x[rs2]
    逻辑左移 R-Type RV32I and RV64I
    把寄存器x[rs1]左移x[rs2]位, 空出的位置补0, 结果写入x[rd]. x[rs2]的低5位代表移动位数, 高位忽略
    +--------------------------------------------------------------------------------------------------+
    |31                   25|24         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        0000000        |     rs2     |     rs1     |   001   |     rd     |        0110011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_sll = opcode_is_0110011 & funct3_is_001 & funct7_is_0000000;

/*
    slli    rd, rs1, shamt                                              x[rd] = x[rs1] << shamt
    立即数逻辑左移 R-Type RV32I and RV64I
    把寄存器x[rs1]左移shamt位, 空出的位置补0, 结果写入x[rd]. 对于RV32I, 仅当shamt[5]=0时, 指令才有效
    +--------------------------------------------------------------------------------------------------+
    |31                   26|25         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        000000         |    shamt    |     rs1     |   001   |     rd     |        0010011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_slli = opcode_is_0010011 & funct3_is_001 & funct7_is_0000000;

/*
    slt    rd, rs1, rs2                                                 x[rd] = x[rs1] < x[rs2]
    小于则置位    R-Type    RV32I and RV64I
    比较x[rs1]和x[rs2]中的数, 如果x[rs1]更小, 向x[rd]写入1, 否则写入0
    +--------------------------------------------------------------------------------------------------+
    |31                   25|24         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        0000000        |     rs2     |     rs1     |   010   |     rd     |        0110011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_slt = opcode_is_0110011 & funct3_is_010 & funct7_is_0000000;

/*
    slti    rd, rs1, imm                                                x[rd] = x[rs1] < sext(imm)
    小于立即数则置位    I-Type RV32I and RV64I
    比较x[rs1]和有符号扩展的立即数, 如果x[rs1]更小, 向x[rd]写入1, 否则写入0
    +--------------------------------------------------------------------------------------------------+
    |31                                 20|19         15|14     12|11         7|6                     0|
    +-------------------------------------+-------------+---------+------------+-----------------------+
    |               imm[11:0]             |     rs1     |   010   |     rd     |        0010011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_slti = opcode_is_0010011 & funct3_is_010;

/*
    sltiu   rd, rs1, imm                                                x[rd] = x[rs1] < uext(imm)
    无符号小于立即数则置位    I-Type RV32I and RV64I
    比较x[rs1]和零扩展的立即数, 比较时视为无符号数, 如果x[rs1]更小, 向x[rd]写入1, 否则写入0
    +--------------------------------------------------------------------------------------------------+
    |31                                 20|19         15|14     12|11         7|6                     0|
    +-------------------------------------+-------------+---------+------------+-----------------------+
    |               imm[11:0]             |     rs1     |   011   |     rd     |        0010011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_sltiu = opcode_is_0010011 & funct3_is_011;

/*
    sltu    rd, rs1, rs2                                                x[rd] = x[rs1] < x[rs2]
    无符号小于则置位    R-Type    RV32I and RV64I
    比较x[rs1]和x[rs2]中的数, 比较时视为无符号数, 如果x[rs1]更小, 向x[rd]写入1, 否则写入0
    +--------------------------------------------------------------------------------------------------+
    |31                   25|24         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        0000000        |     rs2     |     rs1     |   011   |     rd     |        0110011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_sltu = opcode_is_0110011 & funct3_is_011 & funct7_is_0000000;

/*
    sra    rd, rs1, rs2                                                 x[rd] = x[rs1] >> x[rs2]
    算术右移 R-Type RV32I and RV64I
    把寄存器x[rs1]右移x[rs2]位, 空位用x[rs1]的最高位填充, 结果写入x[rd]. x[rs2]的低5位代表移动位数, 高位忽略
    +--------------------------------------------------------------------------------------------------+
    |31                   25|24         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        0100000        |     rs2     |     rs1     |   101   |     rd     |        0110011        |
    +--------------------------------------------------------------------------------------------------+
*/
assign      instr_sra = opcode_is_0110011 & funct3_is_101 & funct7_is_0100000;

/*
    srai    rd, rs1, shamt                                              x[rd] = x[rs1] >> shamt
    立即数算术右移 R-Type RV32I and RV64I
    把寄存器x[rs1]右移shamt位, 空位用x[rs1]的最高位填充, 结果写入x[rd]. 仅当shamt[5]=0时有效
    +--------------------------------------------------------------------------------------------------+
    |31                   26|25         20|19         15|14     12|11         7|6                     0|
    +-----------------------+-------------+-------------+---------+------------+-----------------------+
    |        010000         |    shamt    |     rs1     |   101   |     rd     |        0010011        |
